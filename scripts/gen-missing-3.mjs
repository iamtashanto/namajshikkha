import { writeFileSync, mkdirSync } from "fs";
function w(eraId, slug, data) {
    mkdirSync(`data/history-details/${eraId}`, { recursive: true });
    writeFileSync(`data/history-details/${eraId}/${slug}.json`, JSON.stringify(data, null, 2), "utf-8");
    const wordCount = data.full_history_bn.join(" ").length;
    console.log(`  ✅ ${eraId}/${slug} — ${wordCount} chars, ${data.full_history_bn.length} paras`);
}

